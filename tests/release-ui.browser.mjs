import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { packageDocx, inspectDocx } from '../lib/redactor/docx.mjs';
import { packageXlsx, inspectXlsx } from '../lib/redactor/xlsx.mjs';
import { workbookModel } from './xlsx-fixtures.mjs';
import { fixturePdf } from './pdf-fixtures.mjs';
const base = process.env.GRA_TEST_URL || 'http://localhost:3100';
