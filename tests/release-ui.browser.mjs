try {
  const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 1440, height: 1000 } });
  const login = await context.request.post(base + '/api/auth/login', { headers: { Origin: base }, data: { email: process.env.GRA_TEST_UI_EMAIL || process.env.GRA_TEST_EMAIL, password: process.env.GRA_TEST_PASSWORD } });
  assert.equal(login.status(), 200);
  const page = await context.newPage(), errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const screenshot = async name => { if (process.env.GRA_TEST_UI_SHOTS) await page.screenshot({ path: `${process.env.GRA_TEST_UI_SHOTS}/${name}.png`, fullPage: true }); };
  await page.goto(base);
  await page.getByRole('link', { name: 'Document Redactor', exact: true }).waitFor();
  await screenshot('workbench-dark');
  await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await screenshot('workbench-light');
  for (const view of ['Runs', 'Approvals', 'Settings', 'Calendar', 'Agents']) await page.getByRole('button', { name: view, exact: true }).click();
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert(await page.locator('.sidebar').evaluate(el => el.getBoundingClientRect().height < innerHeight / 2));
  await page.getByRole('button', { name: 'Query Inbox', exact: true }).click();
  await page.getByRole('button', { name: 'Agents', exact: true }).click();
  await screenshot('workbench-mobile');
  await page.getByRole('link', { name: 'Document Redactor', exact: true }).click();
  await page.getByRole('heading', { name: 'GRA Secure Document Redactor' }).waitFor();
  await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).waitFor();
  assert.equal(await page.locator('html').getAttribute('data-theme'), 'light');
  await screenshot('redactor-empty-mobile');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Switch to dark theme', exact: true }).click();
  await screenshot('redactor-empty-dark');
  const requests = []; page.on('request', r => requests.push({ url: r.url(), body: r.postData(), method: r.method() }));
  const upload = (buffer, name, mimeType) => page.locator('#document-upload').setInputFiles({ name, mimeType, buffer: Buffer.from(buffer) });
  const readDownload = async action => { const event = page.waitForEvent('download'); await action(); const download = await event, chunks = []; for await (const c of await download.createReadStream()) chunks.push(c); return new Uint8Array(Buffer.concat(chunks)); };
  const docx = packageDocx({ paragraphs: ['Synthetic client information sheet', 'Invoice INV-2026-001', 'PAN ABCDE1234F', 'Amount INR 42000'].map(text => ({ props: {}, runs: [{ props: {}, text }] })), section: {} });
  const dropped = await page.evaluateHandle(bytes => { const transfer = new DataTransfer(); transfer.items.add(new File([new Uint8Array(bytes)], 'synthetic-client-information.docx', { type: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' })); return transfer; }, Array.from(docx));
  await page.getByRole('region', { name: 'Local document upload', exact: true }).dispatchEvent('drop', { dataTransfer: dropped });
  await dropped.dispose();
  await page.getByRole('button', { name: 'Locate DOCX proposal 1', exact: true }).click();
  assert.equal(await page.locator('#manual-selection').evaluate(el => el.value.slice(el.selectionStart, el.selectionEnd)), 'ABCDE1234F');
  assert.equal(await page.locator('#manual-selection').evaluate(el => getComputedStyle(el).outlineStyle), 'solid');
  await page.getByRole('checkbox').check();
  const docOutput = await readDownload(() => page.getByRole('button', { name: 'Verify & download DOCX', exact: true }).click());
  assert(!inspectDocx(docOutput, 'output.docx').text.includes('ABCDE1234F'));
  await page.getByRole('button', { name: 'Remove proposal 1', exact: true }).click();
  assert.equal(await page.locator('.is-verified').count(), 0, 'Changed decisions clear successful-download status');

  const model = workbookModel();
  model.sheets[0].name = 'Synthetic Balance Sheet';
  model.sheets[0].rows = Array.from({ length: 240 }, (_, i) => ({ index: i + 1, height: null, hidden: i === 1 }));
  model.sheets[0].cells = Array.from({ length: 240 }, (_, i) => ({ ref: `A${i + 1}`, value: i === 124 ? 'GSTIN 27ABCDE1234F1Z5' : `Synthetic balance line ${i + 1}`, kind: 'text', style: 0, formula: null, rowHidden: i === 1, columnHidden: false }));
  await upload(packageXlsx(model), 'synthetic-gst-balance.xlsx', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
  await page.locator('#xlsx-address').fill('a125');
  await page.locator('#xlsx-address').press('Enter');
  await screenshot('xlsx-navigation');
  assert.equal(await page.locator('.xlsx-pages span').textContent(), 'Page 2 of 3', `Cell navigation failed; errors: ${await page.locator('.redactor-error').allTextContents()}`);
  await page.getByRole('button', { name: 'Select A125 value', exact: true }).waitFor();
  assert.match(await page.locator('#xlsx-selection').inputValue(), /27ABCDE1234F1Z5/);
  await page.getByRole('button', { name: 'Next stored cell', exact: true }).click();
  assert.match(await page.locator('#xlsx-selection').inputValue(), /126/);
  await page.getByRole('button', { name: 'Previous stored cell', exact: true }).click();
  await page.locator('#xlsx-address').fill('Z999'); await page.getByRole('button', { name: 'Go to cell', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'stored cell is not present' }).waitFor();
  await page.locator('#xlsx-sheet').selectOption('2');
  assert.match(await page.locator('.xlsx-sheet-state').textContent(), /veryHidden/);
  await screenshot('xlsx-hidden-dark');
  for (const index of ['0', '1', '2']) { await page.locator('#xlsx-sheet').selectOption(index); await page.getByRole('checkbox', { name: 'I reviewed this worksheet, including hidden data.', exact: true }).check(); }
  await page.getByRole('checkbox', { name: /^I reviewed every worksheet and selected removal/ }).check();
  const bookOutput = await readDownload(() => page.getByRole('button', { name: 'Verify & download XLSX', exact: true }).click());
  const rebuilt = inspectXlsx(bookOutput, 'output.xlsx');
  assert.equal(rebuilt.sheets[0].cells.length, 240);
  assert(!rebuilt.sheets[0].cells.find(c => c.ref === 'A125').value.includes('27ABCDE1234F1Z5'));

  const pdf = fixturePdf({ pages: ['Synthetic tax invoice INV-2026-001\nPAN ABCDE1234F\nTotal INR 42000'] });
  await upload(pdf, 'synthetic-invoice.pdf', 'application/pdf');
  await page.getByRole('heading', { name: 'PDF page review', exact: true }).waitFor({ timeout: 50000 });
  const preview = page.locator('.pdf-preview');
  const coords = async () => Object.fromEntries(await Promise.all(['x', 'y', 'width', 'height'].map(async k => [k, Number(await page.locator(`#pdf-${k}`).inputValue())])));
  await page.getByRole('button', { name: 'Load PDF region 1', exact: true }).click();
  const original = await coords();
  await page.getByRole('checkbox', { name: 'I reviewed this entire PDF page and all proposed regions.', exact: true }).check();
  assert(await page.getByRole('checkbox', { name: /^I reviewed every PDF page/ }).isDisabled(), 'Unapplied draft blocks final review');
  await page.getByRole('button', { name: 'Zoom in PDF', exact: true }).click();
  await page.getByRole('button', { name: 'Zoom in PDF', exact: true }).click();
  await page.getByRole('button', { name: 'Zoom in PDF', exact: true }).click();
  assert.deepEqual(await coords(), original, 'Zoom never rescales export coordinates');
  await page.locator('.pdf-viewport').evaluate(el => { el.scrollLeft = 50; el.scrollTop = 20; });
  const pageBox = await preview.boundingBox(), regionBox = await page.locator('.pdf-region:not(.pdf-draft)').first().boundingBox();
  assert(Math.abs((regionBox.x - pageBox.x) / pageBox.width * 800 - original.x) < 1);
  await preview.focus(); await page.keyboard.press('ArrowRight'); await page.keyboard.press('Shift+ArrowDown');
  assert.equal((await coords()).x, original.x + 1); assert.equal((await coords()).height, original.height + 1);
  await page.getByRole('button', { name: 'Apply to loaded region', exact: true }).click();
  await page.getByRole('button', { name: 'Load PDF region 1', exact: true }).click();
  const resized = await coords();
  await page.locator('.pdf-viewport').evaluate(el => { el.scrollLeft = 0; el.scrollTop = 0; });
  const handle = page.locator('.pdf-resize-handle'); await handle.scrollIntoViewIfNeeded(); const h = await handle.boundingBox();
  await page.mouse.move(h.x + h.width / 2, h.y + h.height / 2); await page.mouse.down(); await page.mouse.move(h.x + h.width / 2 + 24, h.y + h.height / 2 + 16); await page.mouse.up();
  assert((await coords()).width > resized.width); assert((await coords()).height > resized.height);
  await page.getByRole('button', { name: 'Apply to loaded region', exact: true }).click();
  await page.getByRole('button', { name: 'Pan page', exact: true }).click();
  await preview.focus(); await page.keyboard.press('ArrowRight');
  assert(await page.locator('.pdf-viewport').evaluate(el => el.scrollLeft > 0));
  await page.getByRole('button', { name: 'Select region', exact: true }).click();
  const edits = await coords();
  await page.setViewportSize({ width: 820, height: 1000 }); assert.deepEqual(await coords(), edits);
  await page.getByRole('checkbox', { name: 'I reviewed this entire PDF page and all proposed regions.', exact: true }).check();
  await page.getByRole('checkbox', { name: /^I reviewed every PDF page/ }).check();
  await page.getByRole('button', { name: 'Fit page', exact: true }).click();
  assert(await page.getByRole('button', { name: 'Verify & download PDF', exact: true }).isEnabled(), 'Viewing changes do not alter approvals');
  await screenshot('pdf-tablet-dark');
  await page.getByRole('button', { name: 'Switch to light theme', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await screenshot('pdf-mobile-light');
  assert(!requests.some(r => r.method !== 'GET' || r.body || r.url.includes('/api/') || /ABCDE|synthetic-invoice|27ABCDE/.test(r.url)));
  assert(!/ABCDE|INV-2026|balance line/.test(await page.evaluate(() => JSON.stringify({ localStorage, sessionStorage }))));
  assert.deepEqual(errors, []);
  console.log('PASS: release UI — shared themes, collapsed mobile navigation, keyboard/focus, realistic synthetic client/invoice/GST/balance documents, DOCX download/status, XLSX large-table navigation/hidden flags, PDF zoom/scroll/resize/pan/keyboard geometry and review preservation; no document API/storage activity.');
  await context.close();
} finally { await browser.close(); }
